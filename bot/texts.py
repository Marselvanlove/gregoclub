# HELPER: Форматирование текстов
# =============================================================================

def format_text(template: str, **kwargs: Any) -> str:
    """
    Форматирует текст с подстановкой переменных.
    Безопасно обрабатывает отсутствующие ключи и ошибки типов.
    """
    try:
        return template.format(**kwargs)
    except (KeyError, ValueError, IndexError) as e:
        # Если ключ отсутствует или неправильный тип — пробуем partial format
        import re
        result = template
        for key, value in kwargs.items():
            # Заменяем простые плейсхолдеры {key}
            result = result.replace(f"{{{key}}}", str(value))
            # Заменяем плейсхолдеры с форматированием {key:.2f} и т.д.
            result = re.sub(rf"\{{{key}:[^}}]+\}}", str(value), result)
        return result
